import 'package:flutter/material.dart';

/// Returns a [SizedBox] with the specified [height].
/// Useful for adding vertical padding between widgets in a [Column].
Widget setHeight(double height) => SizedBox(height: height);

/// Returns a [SizedBox] with the specified [width].
/// Useful for adding horizontal padding between widgets in a [Row].
Widget setWidth(double width) => SizedBox(width: width);
